#!/usr/bin/env python3
"""R2-M3 (v3.99): the ACA control geometry, repaired and verified.

Referee 2 required the ACA windows to be re-extracted on the correct 7 m
geometry rather than compensated for by argument. That has now been done:
278 blocks (265 ACA + the 52 holding the 75 threshold crossings, overlapping
by 39), 739 GB, re-fetched, re-calibrated and re-searched with the frozen
pipeline and a corrected extractor.

The correction, pre-specified before the run in ACA_REEXTRACTION_SPEC.md:
the dish diameter now comes from ANTENNA::DISH_DIAMETER and the maximum
baseline from UVW, so both theta_PB and theta_syn are measured from the data,
and the control annulus starts at

    max(0.14 theta_PB, 2.0 theta_syn)

so that no control position lies on the star's own synthesised main lobe.
ANN_SYN_FACTOR = 2.0 was fixed in advance and has not been adjusted.

This generator reads the corrected products and emits the numbers the paper
quotes. It asserts the pre-registered success criterion so that the claim in
the text cannot outrun the measurement.

Writes survey_numbers_round64.tex.
"""
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'survey_numbers_round64.tex')
TRIG = 5.0

W = json.load(open(os.path.join(HERE, 'acareext_v399.json')))
aca = [w for w in W if w['dish'] < 10]
twm = [w for w in W if w['dish'] >= 10]
assert aca, 'no corrected ACA windows found'


def rank(w):
    return (w['ge'] + 1.0) / (w['n'] + 1.0)


def ks(u):
    u = sorted(u)
    n = len(u)
    D = max(max((i + 1) / n - x, x - i / n) for i, x in enumerate(u))
    lam = (math.sqrt(n) + 0.12 + 0.11 / math.sqrt(n)) * D
    p = 2 * sum((-1) ** (k - 1) * math.exp(-2 * k * k * lam * lam)
                for k in range(1, 101))
    return D, max(0.0, min(1.0, p))


u = [rank(w) for w in aca]
D, p = ks(u)
med = sorted(u)[len(u) // 2]

# THE PRE-REGISTERED CRITERION. If this ever fails, the paper must not claim
# the screen was repaired, and the build should stop rather than print it.
assert p > 0.05, (
    'the corrected ACA stellar ranks are still inconsistent with uniformity '
    '(D=%.3f, p=%.4f). The pre-specified success criterion was p > 0.05. Do '
    'not weaken the criterion; report the failure.' % (D, p))

# stage-1 under the corrected screen: reaches the trigger AND outranks every
# control -- the same definition used throughout the paper
s1 = [w for w in aca if w['star'] and w['star'] >= TRIG and w['ge'] == 0]
s1.sort(key=lambda w: -w['star'])

import sys as _sys
_sys.path.insert(0, HERE)
import maskframe_v411 as _mf                                 # noqa: E402


_STAR_AT = {}
for _r in json.load(open(os.path.join(HERE, 'corrected_export_v399.json')))['rows']:
    _STAR_AT.setdefault((_r['eb'], round(float(_r['flo']), 4),
                         round(float(_r['fhi']), 4)), set()).add(_r['star_name'])


def dv_kms(w):
    """The stellar-frame offset of an ACA window's peak, through the chain
    the paper adopts.  ★ r27 row 46: this was three hard-coded carbon
    monoxide rest frequencies compared with a TOPOCENTRIC peak, i.e. the mask
    in the observer's frame against a list that is not the mask."""
    f = w.get('pkf') or 0.0
    if not f:
        return None
    vb, _s = _mf.vbary(w['eb'], w['flo'])
    #: ★ r27 merge: the re-extracted ACA records carry no star name (`star`
    #: is the window's statistic), so the star is found by POSITION -- the
    #: execution block and the window's own frequency edges -- in the
    #: corrected export, never by a name; a window that does not resolve to
    #: exactly one star gets no stellar-frame offset and is not attributed.
    _st = _STAR_AT.get((w['eb'], round(float(w['flo']), 4),
                        round(float(w['fhi']), 4)), set())
    if len(_st) != 1:
        return None
    vs, _t, _b = _mf.vsys(next(iter(_st)))
    if vb is None or vs is None:
        return None
    _fb, fstar = _mf.to_stellar(f, vb, vs)
    name, _f0, dv = _mf.nearest(fstar)
    return name, dv


attributed, unattributed = [], []
assert all(len(_STAR_AT.get((w['eb'], round(float(w['flo']), 4),
                             round(float(w['fhi']), 4)), ())) == 1
           for w in s1), 'a stage-1 ACA window does not resolve to one star'
for w in s1:
    d = dv_kms(w)
    (attributed if d and abs(d[1]) <= _mf.MASK_HALF_KMS
     else unattributed).append(w)

L = ['%% GENERATED by acafix_v399.py -- do not hand-edit.\n']


def m(k, v):
    L.append('\\newcommand{\\%s}{%s}\n' % (k, v))


m('FixNBlocks', '%d' % len({w['eb'] for w in W}))
m('FixNWin', '%d' % len(W))
m('FixNAcaWin', '%d' % len(aca))
m('FixNTwmWin', '%d' % len(twm))
m('FixKsD', '%.3f' % D)
m('FixKsP', '%.2f' % p)
m('FixMedRank', '%.3f' % med)
m('FixNStageOne', '%d' % len(s1))
m('FixNAttrib', '%d' % len(attributed))
m('FixNUnattrib', '%d' % len(unattributed))
m('FixAnnFactor', '2.0')
m('FixTB', '%.2f' % 0.739)

# ---------------------------------------------------------------------------
# v4.03: WHICH GEOMETRY THE RELEASED CATALOGUE ACTUALLY CARRIES.
#
# The appendices described the 12 m-beam control geometry in the present
# tense, as a defect still standing, while the same appendix quoted the
# after-repair rank test four hundred lines earlier.  Whether that text was
# stale could not be settled by reading it: it needs the provenance of the
# rows the catalogue ships.  corrected_export_v399.py stamps every row it
# replaces with `provenance = corrected-geometry`, and v342_calc builds the
# catalogue from that export, so the question has an exact answer and this
# is where it is computed rather than asserted in prose.
_EXP = {}
for _r in json.load(open(os.path.join(HERE,
                                      'corrected_export_v399.json')))['rows']:
    _lo, _hi = sorted((float(_r['flo']), float(_r['fhi'])))
    _EXP[(_r['eb'], round(_lo, 3), round(_hi, 3))] = _r.get('provenance')
_META = json.load(open(os.path.join(HERE, 'archive_meta_v381.json')))['ebs']
import csv as _csv
_CAT = list(_csv.DictReader(open(os.path.join(
    HERE, 'per_target_results_v3.99.csv'))))
_aca_tot = _aca_fix = 0
_left = []
for _r in _CAT:
    if _META.get(_r['eb'], {}).get('array') != '7m':
        continue
    _lo, _hi = sorted((float(_r['flo_GHz']), float(_r['fhi_GHz'])))
    _aca_tot += 1
    if _EXP.get((_r['eb'], round(_lo, 3), round(_hi, 3))) == 'corrected-geometry':
        _aca_fix += 1
    else:
        _left.append(_r['star_name'])
assert _aca_tot and _aca_fix, 'no ACA window in the catalogue carries a geometry'
# The paper says the repair reaches all but a handful.  Fail if that stops
# being true, in either direction: a jump back towards the frozen geometry
# means the export regressed, and a drop to zero left-over means the
# sentence naming them has to go.
assert _aca_fix >= 0.99 * _aca_tot, (
    'only %d of %d catalogue ACA windows carry the repaired control '
    'geometry; the appendix text says essentially all of them do'
    % (_aca_fix, _aca_tot))
m('FixNCatAca', '%d' % _aca_tot)
m('FixNCatAcaFixed', '%d' % _aca_fix)
m('FixNCatAcaLeft', '%d' % (_aca_tot - _aca_fix))
m('FixCatAcaLeftStar', sorted(set(_left))[0] if _left else 'none')
for tag, w in (('Hd', 'A002_Xc26103_X155a'), ('Bp', 'A002_X6f1341_X1484'),
               ('Vir', 'A002_Xc079b5_X82f')):
    q = [x for x in s1 if x['eb'] == w]
    if q:
        d = dv_kms(q[0])
        m('FixT%s' % tag, '%.1f' % q[0]['star'])
        m('FixDv%s' % tag, '%+.0f' % d[1])
open(OUT, 'w').writelines(L)

print('acafix: %d blocks, %d windows (%d ACA, %d 12 m)'
      % (len({w['eb'] for w in W}), len(W), len(aca), len(twm)))
print('  ACA ranks: D=%.3f p=%.4f median %.3f  -> PASS (criterion p>0.05)'
      % (D, p, med))
print('  stage-1 under the corrected screen: %d (%d line-attributed, '
      '%d unattributed)' % (len(s1), len(attributed), len(unattributed)))
for w in s1:
    d = dv_kms(w)
    print('     %-22s T*=%6.2f  %s %+.1f km/s'
          % (w['eb'], w['star'], d[0] if d else '--', d[1] if d else 0))

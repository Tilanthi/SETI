#!/usr/bin/env python3
"""flagdecl_r27.py -- the two declared calibration omissions, as macros.

Reads the frozen record r27inputs/flags_r27.json (the measurements of
FLAGS.md and LEGACY.md) and emits survey_numbers_round1290.tex.  The paper
states both omissions from these macros and types no number.  Assertions:
D1 the fallen crossings listed sum to the count printed; D2 every fallen
crossing is unattributed (attributed ones would change the attribution
census, which this declaration does not cover); D3 no new crossing appeared;
D4 the deepest limit is unchanged at printed precision (< 1 per cent).
--drive N perturbs one input in memory and writes a _driveN file only.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DRIVE = int(sys.argv[sys.argv.index('--drive') + 1]) if '--drive' in sys.argv else None
SFX = '' if DRIVE is None else '_drive%d' % DRIVE
R = json.load(open(os.path.join(HERE, 'r27inputs', 'flags_r27.json')))
F, L = R['flags'], R['legacy_flux']
if DRIVE == 1:
    F['n_crossings_below_trigger'] += 1
if DRIVE == 2:
    F['fallen'][1]['status'] = 'attributed'
if DRIVE == 3:
    F['n_new_crossings'] = 1
if DRIVE == 4:
    F['deepest_limit_change_pct'] = 5.0
fail = []


def ck(name, ok, detail=''):
    print('  %s %s  %s' % (name, 'PASS' if ok else 'FAIL', detail))
    if not ok:
        fail.append(name)


ck('D1 the fallen crossings sum to the printed count',
   sum(x['n'] for x in F['fallen']) == F['n_crossings_below_trigger'],
   '%d listed, %d printed' % (sum(x['n'] for x in F['fallen']),
                              F['n_crossings_below_trigger']))
ck('D2 every fallen crossing is unattributed',
   all(x['status'].startswith('unattributed') for x in F['fallen']))
ck('D3 no new crossing appeared', F['n_new_crossings'] == 0)
ck('D4 the deepest limit is unchanged at printed precision',
   F['deepest_limit_change_pct'] < 1.0, '%g per cent' % F['deepest_limit_change_pct'])
W = ('no', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine')
M = {'FgNEbMeas': '%d' % F['n_eb_recalibrated'],
     'FgNCrossMeas': '%d' % F['n_crossings_measured'],
     'FgNCrossFall': '%d' % F['n_crossings_below_trigger'],
     'FgNCrossFallWord': W[F['n_crossings_below_trigger']],
     'FgLimDeepMaxPct': '%d' % F['max_rms_increase_pct'],
     'LgNEbFlux': '%d' % L['n_eb_affected'],
     'LgNEbFluxWord': W[L['n_eb_affected']],
     'LgFluxMaxPct': '%.1f' % L['max_too_bright_pct']}
out = ['%% GENERATED by flagdecl_r27.py (round 1290) -- do not hand-edit.']
out += ['\\newcommand{\\%s}{%s}' % kv for kv in sorted(M.items())]
open(os.path.join(HERE, 'survey_numbers_round1290%s.tex' % SFX), 'w').write('\n'.join(out) + '\n')
print('flagdecl_r27: %d macros, %d assertion(s) failed %s' % (len(M), len(fail), fail))
sys.exit(1 if fail else 0)

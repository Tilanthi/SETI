#!/usr/bin/env python3
"""The top level of the version directory, owned by the chain (v4.28 re-root).

Since v4.28 the build lives in `chain/` and the version directory's top level
holds only what an author or a reader needs to SEE: the PDF, the deposit, a
README and four thin wrappers.  Two of those are copies of chain products,
and a copy that can drift is the failure the re-root was made to fix -- the
file a reader can see must be the file the paper is.  So:

  --sync   the LAST step of `make_all.sh` and of `gate.sh`: write the PDF and
           deposit copies from chain/, and regenerate the wrappers and README
           from the templates below.  Never hand-copied.
  --check  a GATE (`g toplevel` in gate.sh): every top-level file must be
           byte-identical to what --sync would write, and nothing else may sit
           at the top level.  A stale PDF copy, an edited wrapper, a stray
           file -- each fails.

In a FLAT tree (this file not inside a directory called `chain`) both modes
say so and exit 0, so the same chain runs unchanged before and after the
re-root.  `--selftest` drives --check both ways in a scratch directory and
requires it to pass on a synced tree and fail on four corruptions.
"""
import hashlib
import os
import shutil
import sys
import tempfile

SUB = 'chain'
DEPOSIT = 'ALMA_Technosignatures_40pc.zip'
EXTRA_TOP = {'.gitignore'}            # kept at the top: patterns apply at any depth
#: ★ v4.29 (Ruling R25): GitHub lists at most 1,000 entries of a directory, and
#: chain/ reached 1,009 before the numbers/ move.  --check fails at or above this
#: count of PUSHED entries (gitignored names, which are never pushed, excluded).
CHAIN_MAX = 1000

WRAP_SH = '''#!/usr/bin/env bash
# WRAPPER, generated by chain/toplevel.py -- do not edit; `gate.sh` fails if
# this file differs from what toplevel.py writes.  The real script is
# chain/%(name)s, which takes its root from $0, so it runs exactly as it did
# before the build moved into chain/.
# ★ $0 is passed ABSOLUTE and the caller's cwd is left alone: the real script
# resolves `dirname "$0"` more than once (gate.sh does `cd "$(dirname "$0")"`
# and then `cd "$(dirname "$0")"` again inside a subshell), so a relative $0
# breaks on the second use.  The first version of this wrapper did exactly that.
exec bash "$(cd "$(dirname "$0")" && pwd)/%(sub)s/%(name)s" "$@"
'''
WRAP_PY = '''#!/usr/bin/env python3
"""WRAPPER, generated by chain/toplevel.py -- do not edit; `gate.sh` fails if
this file differs from what toplevel.py writes.  The real script is
chain/cleanregen.py, which chdirs to its own directory; every argument
(--verdict, --keep) is passed through unchanged."""
import os
import sys

_real = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                     '%(sub)s', 'cleanregen.py')
os.execv(sys.executable, [sys.executable, _real] + sys.argv[1:])
'''
README = '''# Searching for technosignatures in the ALMA archive — paper version directory

* **The paper:** [`%(stem)s.pdf`](%(stem)s.pdf)
* **The machine-readable deposit:** [`%(dep)s`](%(dep)s)

Both are byte-identical copies of the files the build writes in `%(sub)s/`. The
copies are made by the build itself (`%(sub)s/toplevel.py --sync`, the last step
of `make_all.sh` and of `gate.sh`) and the gate battery fails if either differs
from its source, so what is shown here is always what the paper is.

## Layout

| path | what it is |
|---|---|
| `%(sub)s/` | the complete build: the manuscript source `%(sub)s/%(stem)s.tex` and `%(sub)s/sections/`, every generator, frozen input, macro file, table and figure, and the gate battery |
| `%(sub)s/notes/` | the written record of the referee rounds: build notes, referee responses, push messages |
| `%(sub)s/OJA_SUBMISSION.md`, `%(sub)s/ARXIV_UPLOAD.md`, `%(sub)s/AUTHOR_ACTIONS.md` | submission notes; they sit beside the gates that check them |
| `make_all.sh`, `gate.sh`, `arxivset.sh`, `cleanregen.py` | thin wrappers that run the real scripts in `%(sub)s/` |

The build was moved into `%(sub)s/` as one unit, so no file's position relative to
any other changed: the regeneration, the gates, the arXiv package and the PDF are
byte-identical to those of the flat tree they came from.

## Rebuilding

```bash
bash make_all.sh                  # regenerate every product
bash gate.sh                      # build the PDF and run the gate battery
python3 cleanregen.py             # delete every product, rebuild twice, compare
bash arxivset.sh <dir> --force    # assemble the arXiv package
```
'''

HERE = os.path.dirname(os.path.abspath(__file__))


def _stem(chain):
    s = [f[:-4] for f in sorted(os.listdir(chain))
         if f.startswith('technosignatures_') and f.endswith('.tex')]
    assert len(s) == 1, 'expected exactly one manuscript .tex, found %r' % s
    return s[0]


def expected(chain):
    """{top-level name: bytes} -- everything --sync writes, nothing else."""
    st = _stem(chain)
    out = {}
    for n in ('make_all.sh', 'gate.sh', 'arxivset.sh'):
        out[n] = (WRAP_SH % {'name': n, 'sub': SUB}).encode()
    out['cleanregen.py'] = (WRAP_PY % {'sub': SUB}).encode()
    out['README.md'] = (README % {'stem': st, 'dep': DEPOSIT,
                                  'sub': SUB}).encode()
    for n in (st + '.pdf', DEPOSIT):
        p = os.path.join(chain, n)
        if os.path.exists(p):
            out[n] = open(p, 'rb').read()
    return out


def sync(chain, top, quiet=False):
    for n, b in expected(chain).items():
        p = os.path.join(top, n)
        if os.path.exists(p) and open(p, 'rb').read() == b:
            continue
        tmp = p + '.toplevel_tmp'
        with open(tmp, 'wb') as fh:
            fh.write(b)
        os.chmod(tmp, 0o755 if n.endswith(('.sh', '.py')) else 0o644)
        os.replace(tmp, p)
        if not quiet:
            print('toplevel: wrote %s' % n)


def chain_entries(chain, top):
    """The chain/ entries the push carries: every name except those the top
    .gitignore excludes (patterns apply at any depth; a trailing / = directory)."""
    import fnmatch
    gi = os.path.join(top, '.gitignore')
    pats = [l.strip().rstrip('/') for l in open(gi).read().splitlines()
            if l.strip() and not l.startswith('#')] if os.path.exists(gi) else []
    # the literal 'chain' (== SUB) keeps numbers_check's classifier reading
    # this as the REAL listing it is, not a macro-layer view to repoint
    assert SUB == 'chain' and os.path.samefile(chain, os.path.join(top, 'chain'))
    return sorted(n for n in os.listdir(os.path.join(top, 'chain'))
                  if not any(fnmatch.fnmatch(n, q) for q in pats))


def check(chain, top, quiet=False, chain_max=None):
    exp = expected(chain)
    bad = []
    cmax = CHAIN_MAX if chain_max is None else chain_max
    nchain = len(chain_entries(chain, top))
    if nchain >= cmax:
        bad.append('%s/ holds %d pushed entries, at or above %d (GitHub lists '
                   'at most 1,000 per directory)' % (SUB, nchain, cmax))
    st = _stem(chain)
    for need in (st + '.pdf', DEPOSIT):
        if need not in exp:
            bad.append('%s does not exist in %s/, so there is nothing to show'
                       % (need, SUB))
    for n, b in sorted(exp.items()):
        p = os.path.join(top, n)
        if not os.path.exists(p):
            bad.append('%s missing at the top level' % n)
        elif open(p, 'rb').read() != b:
            bad.append('%s differs from %s -- %s' % (
                n, ('%s/%s' % (SUB, n)) if n in (st + '.pdf', DEPOSIT)
                else 'the template in toplevel.py',
                'the copy a reader sees is not the file the paper is'
                if n.endswith(('.pdf', '.zip')) else 'a wrapper was edited'))
    allowed = set(exp) | {SUB} | EXTRA_TOP
    for n in sorted(os.listdir(top)):
        if n not in allowed:
            bad.append('%s at the top level is not one of the %d files the '
                       'chain owns there' % (n, len(allowed)))
    if not quiet:
        h = lambda b: hashlib.sha256(b).hexdigest()[:12]
        print('toplevel: %d owned top-level files; PDF %s, deposit %s; '
              '%s/ %d pushed entries (limit < %d)'
              % (len(exp), h(exp.get(st + '.pdf', b'')),
                 h(exp.get(DEPOSIT, b'')), SUB, nchain, cmax))
        for b in bad:
            print('  FAIL %s' % b)
        print('toplevel: %d FAIL' % len(bad))
    return bad


def selftest():
    d = tempfile.mkdtemp(prefix='toplevel_selftest_')
    try:
        c = os.path.join(d, SUB)
        os.makedirs(c)
        open(os.path.join(c, 'technosignatures_x.tex'), 'w').write('x')
        open(os.path.join(c, 'technosignatures_x.pdf'), 'wb').write(b'%PDF1')
        open(os.path.join(c, DEPOSIT), 'wb').write(b'PK1')
        sync(c, d, quiet=True)
        ok = not check(c, d, quiet=True)
        cases = []
        open(os.path.join(c, 'technosignatures_x.pdf'), 'wb').write(b'%PDF2')
        cases.append(('stale PDF copy', bool(check(c, d, quiet=True))))
        sync(c, d, quiet=True)
        open(os.path.join(d, 'gate.sh'), 'a').write('# edited\n')
        cases.append(('edited wrapper', bool(check(c, d, quiet=True))))
        sync(c, d, quiet=True)
        open(os.path.join(d, 'stray.txt'), 'w').write('x')
        cases.append(('stray top-level file', bool(check(c, d, quiet=True))))
        os.remove(os.path.join(d, 'stray.txt'))
        os.remove(os.path.join(d, DEPOSIT))
        cases.append(('missing deposit copy', bool(check(c, d, quiet=True))))
        sync(c, d, quiet=True)
        for i in range(CHAIN_MAX):
            open(os.path.join(c, 'f%04d' % i), 'w').close()
        cases.append(('chain/ at %d entries' % CHAIN_MAX,
                      bool(check(c, d, quiet=True))))
        open(os.path.join(d, '.gitignore'), 'w').write('f0*\n')
        cases.append(('gitignored entries not counted',
                      not check(c, d, quiet=True)))
        # FUNCTIONAL: a wrapper must deliver an absolute $0 that survives the
        # double-dirname idiom the real chain scripts use, from ANY cwd.
        import subprocess
        open(os.path.join(c, 'gate.sh'), 'w').write(
            'cd "$(dirname "$0")"\nV=$(cd "$(dirname "$0")" && pwd)\n'
            'echo "$V"\n')
        r = subprocess.run(['bash', os.path.join(d, 'gate.sh')],
                           capture_output=True, text=True, cwd='/')
        func = (r.returncode == 0 and
                os.path.realpath(r.stdout.strip()) == os.path.realpath(c))
        # (the broken first wrapper EXITED 0 here and printed nothing: the
        # check is on the resolved path, never on the return code)
        res = ok and all(f for _n, f in cases) and func
        print('toplevel --selftest: synced tree passes: %s; %s -> %s'
              % (ok, ', '.join('%s caught: %s' % c for c in cases[:6]) +
                 '; wrapper works from cwd=/: %s' % func,
                 'PASS' if res else 'FAIL'))
        return res
    finally:
        shutil.rmtree(d)


if __name__ == '__main__':
    if '--selftest' in sys.argv:
        sys.exit(0 if selftest() else 1)
    if os.path.basename(HERE) != SUB:
        print('toplevel: flat tree (not inside %s/), nothing to %s'
              % (SUB, 'sync' if '--sync' in sys.argv else 'check'))
        sys.exit(0)
    TOP = os.path.dirname(HERE)
    if '--sync' in sys.argv:
        sync(HERE, TOP)
        sys.exit(0)
    _cm = (int(sys.argv[sys.argv.index('--chain-max') + 1])
           if '--chain-max' in sys.argv else None)
    sys.exit(1 if check(HERE, TOP, chain_max=_cm) else 0)

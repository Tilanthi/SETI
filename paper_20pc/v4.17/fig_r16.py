ROUND = 680

# D36: a test must never write to a path production reads.  The suffix
# follows the FLAG, not the perturbation.
DRIVE = int(sys.argv[sys.argv.index('--drive') + 1]) if '--drive' in sys.argv \
    else None
SUF = '' if DRIVE is None else '_drive%d' % DRIVE

# --------------------------------------------------------------- macro layer
_VALS = {}
for _f in sorted(glob.glob(os.path.join(HERE, 'survey_numbers*.tex'))):
    if '_drive' in os.path.basename(_f):
        continue
    for _n, _v in re.findall(
            r'\\(?:new|renew|provide)command\*?\{\\([A-Za-z]+)\}'
            r'\{((?:[^{}]|\{[^{}]*\})*)\}',
            open(_f, encoding='utf8', errors='ignore').read()):
        if _v.strip():
            _VALS[_n] = _v.strip()


def texval(name):
    if name not in _VALS:
        raise SystemExit('fig_r16: macro \\%s is not published' % name)
    return _VALS[name]


def texnum(name):
    return float(re.sub(r'[^0-9.eE+-]', '', texval(name)
                        .replace(r'\times10^{', 'e')
                        .replace(r'\times 10^{', 'e')))


def texround(name):
    """(value, half a unit in the macro's own last printed place).  A figure
    of merit published to two significant figures reproduces when the
    recomputation lands inside its own rounding, not inside a percentage of
    my choosing."""
    t = texval(name).replace(' ', '')
    mm = re.match(r'([-\d.]+)\\times10\^\{(-?\d+)\}$', t)
    if not mm:
        dp = len(t.split('.')[1]) if '.' in t else 0
        return float(t), 0.5 * 10.0 ** (-dp)
    mant, ex = mm.group(1), int(mm.group(2))
    dp = len(mant.split('.')[1]) if '.' in mant else 0
    return float(mant) * 10.0 ** ex, 0.5 * 10.0 ** (ex - dp)


def sci(x, nd=2):
    e = int(math.floor(math.log10(abs(x))))
    return r'%.*f\times10^{%d}' % (nd - 1, x / 10.0 ** e, e)


fail = []


def ck(name, ok, detail=''):
    print('  %-4s %s\n       %s' % ('PASS' if ok else 'FAIL', name, detail))
    if not ok:
        fail.append(name.split()[0])


# =====================================================================
# 1.  MARGOT et al.'s LIMIT, READ FROM THE TABLE THE PAPER PRINTS
# =====================================================================
# The module is imported, not run: it guards its own main().  This is the
# same import `occurrence_v399.py` already uses for the threshold factors,
# so the EIRP now comes from the same place the factor does.
import make_fig_context_v410 as _ctx          # noqa: E402

_MAR = _ctx.LIT['margot2023']
# the deepest published limit, which is the convention `thresholds_table`
# uses for the cell Table 1 prints
E_MAR = min(p[1] for p in _MAR['pts'])
SNR_MAR = _MAR['snr']
SCALE_MAR = _ctx.scale_to_common('margot2023')
NU_LO, NU_HI = _MAR['freq_GHz']

# --- F1: the value the Discussion uses is the cell Table 1 prints ---------
_tab = open(os.path.join(HERE, 'tab_litthresh_r15.tex'),
            encoding='utf8').read()
_row = [ln for ln in _tab.splitlines() if 'Margot' in ln]
assert len(_row) == 1, 'Table 1 has %d Margot rows' % len(_row)
_cells = [c.strip() for c in _row[0].split('&')]
TAB_EIRP = float(re.sub(r'[^0-9.eE+-]', '',
                        _cells[4].replace(r'\times10^{', 'e')))
TAB_EIRP_FIVE = float(re.sub(r'[^0-9.eE+-]', '',
                             _cells[5].replace(r'\times10^{', 'e')))
_v = E_MAR if DRIVE != 1 else 1.0e13
ck('F1 the EIRP the Discussion evaluates the figure of merit on is the cell '
   'Table 1 prints for the same programme, to the digit',
   abs(_v / TAB_EIRP - 1.0) < 1e-9
   and abs(TAB_EIRP_FIVE / (TAB_EIRP * SCALE_MAR) - 1.0) < 1e-9,
   'Discussion %.4g against Table 1 %.4g; Table 1 at five %.4g against '
   '%.4g x %.2f' % (_v, TAB_EIRP, TAB_EIRP_FIVE, TAB_EIRP, SCALE_MAR))

# --- F2: and it is the value in Margot et al.'s own sentence -------------
_e = E_MAR if DRIVE != 2 else 1.0e13
_ex = int(math.floor(math.log10(_e)))
_lit = ('%g x 10^%d' % (_e / 10.0 ** _ex, _ex))
_quotes = (_MAR['src'], _MAR['snr_src'])
ck('F2 that EIRP appears verbatim in the sentences of Margot et al. recorded '
   'beside it, so it is read from their paper and not from a summary of it',
   all(_lit in q for q in _quotes) and len(_quotes[0]) > 80,
   'looking for %r in both recorded quotations: %s'
   % (_lit, [(_lit in q) for q in _quotes]))

# --- their figure of merit, on the quantities they publish ---------------
ZETA_AO = (texnum('FomNormN') * texnum('FomNormNuRel')
           / texnum('FomAreciboEirp'))
N_MAR = texnum('FomMargotN')
NUREL_MAR = (NU_HI - NU_LO) / (0.5 * (NU_HI + NU_LO))
CW_MAR = ZETA_AO * E_MAR / (N_MAR * NUREL_MAR)
CW_MAR_FIVE = CW_MAR * SCALE_MAR

_v = SCALE_MAR if DRIVE != 3 else 1.0
ck('F3 their figure of merit is the published expression on the three '
   'quantities they publish, the common-basis one is that value times the '
   'ratio of thresholds and nothing else, and both lie below the Enriquez '
   'et al. value the sentence compares them with',
   abs(_v - 5.0 / SNR_MAR) < 1e-12
   and abs(CW_MAR * _v / (ZETA_AO * E_MAR * _v / (N_MAR * NUREL_MAR)) - 1.0)
   < 1e-12
   and CW_MAR * _v < texnum('FomLitEnriquezFive') < texnum('FomLitEnriquez')
   and abs(NUREL_MAR - (NU_HI - NU_LO) / (0.5 * (NU_HI + NU_LO))) < 1e-12,
   'zeta %.3g, N %.0f, nu_rel %.4f -> %.4f published, x%.2f -> %.4f at five; '
   'Enriquez %.3f -> %.3f'
   % (ZETA_AO, N_MAR, NUREL_MAR, CW_MAR, _v, CW_MAR * _v,
      texnum('FomLitEnriquez'), texnum('FomLitEnriquezFive')))


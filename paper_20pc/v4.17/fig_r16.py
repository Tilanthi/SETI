# 2.  THE GAP, ON THE BASIS THE PARAGRAPH DECLARES
# =====================================================================
import adopted_e90 as _ae                     # noqa: E402

CAT = list(csv.DictReader(open(os.path.join(
    HERE, 'per_target_results_v3.99.csv'))))
A = [r for r in CAT if r['search_class'] == 'A']
E90 = _ae.per_window(CAT, HERE)


def _union(iv):
    iv = sorted((min(a, b), max(a, b)) for a, b in iv)
    tot, (clo, chi) = 0.0, iv[0]
    for a, b in iv[1:]:
        if a > chi:
            tot += chi - clo
            clo, chi = a, b
        else:
            chi = max(chi, b)
    return tot + chi - clo


_iv = [(float(r['flo_GHz']), float(r['fhi_GHz'])) for r in A]
_lo = min(min(a, b) for a, b in _iv)
_hi = max(max(a, b) for a, b in _iv)
NUREL = _union(_iv) / (0.5 * (_lo + _hi))
NSYS = len({r['system_id'] for r in A})


def per_system(which):
    """The deepest window of each system, on one of the two conventions.
    Keyed on the system identifier and never on a name."""
    d = {}
    for r in A:
        v = E90[id(r)] if which == 'e90' else float(r['eirp_nominal_W'])
        if v and v < d.get(r['system_id'], float('inf')):
            d[r['system_id']] = v
    return sorted(d.values())


def cwtfm(e):
    return ZETA_AO * e / (NSYS * NUREL)


BARE = per_system('bare')
ADOPT = per_system('e90')
CW_BARE_MED, CW_BARE_HI = cwtfm(st.median(BARE)), cwtfm(BARE[-1])
CW_AD_MED, CW_AD_HI = cwtfm(st.median(ADOPT)), cwtfm(ADOPT[-1])

EN_PUB, EN_FIVE = texnum('FomLitEnriquez'), texnum('FomLitEnriquezFive')
# the gap the paragraph quotes, on the bare-threshold basis it declares
GAP_PUB, GAP_FIVE = CW_BARE_MED / EN_PUB, CW_BARE_MED / EN_FIVE
# and the same two on the EIRP_90 basis, which the paragraph names as such
GAP90_PUB, GAP90_FIVE = CW_AD_MED / EN_PUB, CW_AD_MED / EN_FIVE

_M = texround('SzCwtfmBareMed')
_W = texround('SzCwtfmBareWorst')
_v = CW_BARE_MED if DRIVE != 4 else CW_AD_MED
ck('F4 the gap is computed from the bare five-sigma branch, which is the '
   'basis the sentence declares: it reproduces the published bare figures of '
   'merit inside their own rounding, it widens when the comparison '
   'programme is rescaled, and it is SMALLER than the EIRP_90 gap quoted '
   'beside it',
   abs(CW_BARE_MED - _M[0]) <= _M[1] and abs(CW_BARE_HI - _W[0]) <= _W[1]
   and _v / EN_FIVE > _v / EN_PUB
   and _v / EN_PUB < GAP90_PUB and _v / EN_FIVE < GAP90_FIVE
   and abs(NUREL - texnum('FomNuRel')) < 5e-4 and NSYS == texnum('NSysClassA'),
   'bare %.4g / %.4g against published %s / %s; gap %.4g -> %.4g against the '
   'EIRP_90 gap %.4g -> %.4g; %d systems at nu_rel %.4f'
   % (CW_BARE_MED, CW_BARE_HI, texval('SzCwtfmBareMed'),
      texval('SzCwtfmBareWorst'), _v / EN_PUB, _v / EN_FIVE,
      GAP90_PUB, GAP90_FIVE, NSYS, NUREL))


#!/usr/bin/env python3
r"""Round 680: THE FIGURE OF MERIT ON ONE BASIS, AND THE DISTANCE RATIO OVER
ONE POPULATION.

Two defects in one paragraph, and both halves are real.

1.  TWO DIFFERENT VALUES OF THE SAME EXTERNAL CONSTANT.  Table 1 gives
    Margot et al. (2023) an EIRP_min of 1.35e13 W, read from their own
    sentence and generated by the same code that draws Figure 1; the
    Discussion evaluated their figure of merit on 1e13 W, typed into
    `occurrence_v399.py` beside the comment "a limit of EIRP > 1e13 W".
    1e13 W is NOT Margot et al.'s limit -- it is the Arecibo planetary radar
    normalisation of the CWTFM itself (`\FomAreciboEirp`), and the two were
    run together.  Margot et al. 2023, AJ 166, 206 state the limit twice,
    sec. 3.6 "transmitters located 326 ly (100 pc) away are detectable with
    0.62 Arecibos (EIRP=1.35 x 10^13 W)" and sec. 6 "fewer than 6.6% of the
    331,312 stars within 100 pc host a transmitter that is detectable in our
    survey (EIRP > 1.35 x 10^13 W)".  Their figure of merit as evaluated here
    is therefore 0.14, not 0.11, and 0.072 rather than 0.053 once their
    S/N = 10 threshold is put on the common basis of five.

    Nothing here is typed: the value is READ from the literature table in
    `make_fig_context_v410.py`, which is the table Figure 1 and Table 1 are
    both drawn from, and F1 requires it to equal the cell Table 1 actually
    prints.  The two can no longer disagree.

2.  A GAP QUOTED ON A BASIS THE SENTENCE DOES NOT USE.  The widening "from
    1.6e4 to 7.9e4" is the ratio of this survey's EIRP_90 figure of merit to
    Enriquez et al.'s, published and rescaled.  But the sentence that carries
    it has just put every programme on a common bare five-sigma threshold and
    calls that the only commensurable footing, and on that footing the survey
    figure is the bare-threshold one (4.4e3, round 270), not the EIRP_90 one
    (1.3e4).  The gap on the basis the paragraph declares is 5.2e3 widening
    to 2.6e4.  Both bases are legitimate and the paper quotes both, but each
    number must be computed on the basis beside it, so this round publishes
    the bare-threshold pair for the sentence that declares a bare threshold
    and leaves the EIRP_90 figures of merit where they already are.

    F4 is the check that keeps them apart: the gap pair must reproduce from
    the BARE branch of the same per-system calculation, must agree with the
    published `\SzCwtfmBareMed` inside its own rounding, and must come out
    SMALLER than the EIRP_90 pair quoted beside it.  Computing it from the
    EIRP_90 branch -- which is what the manuscript did -- makes that last
    clause false, and drive 4 does exactly that.

3.  MINOR 12: "between 25 and 277 times further away than the stars searched
    here" is measured over the CARRIER search and described as the survey.
    277x is tau Cet at 3.652 pc; the surveyed sample reaches Proxima Cen at
    1.302 pc, which is 776x.  The arithmetic is right and the label is wrong,
    which is the third place in this paper where a ratio has been computed
    over one population and described as another, so F5 ties the label to the
    measurement rather than fixing the number: the published ratio must
    reproduce from the nearest star OF THE CARRIER SEARCH, and the sample
    must contain a nearer star that is not in it, so that the population
    cannot be dropped from the sentence again.

Six assertions, six drives, each driven to fail on its own.
"""

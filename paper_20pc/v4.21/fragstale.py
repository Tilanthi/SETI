#!/usr/bin/env python3
r"""Gate: no generated fragment may be older than the generator that owns it.

The ledger fragment and the mask ladder were the same failure one file
apart: a `tab_*.tex` or a frozen `*.json` still on disk from a run of its
generator that happened before the inputs changed. Both looked
authoritative -- both were generated, both carried a "do not hand-edit"
header -- and both disagreed with the analysis the paper now describes. A
generated file is not thereby current; it is only a record of the last time
someone ran something.

Nothing checked this, so this does, three ways:

  S1  every generated fragment the manuscript inputs declares a generator
      in its own header, and that generator exists;
  S2  no fragment is older than its generator, than the catalogue, or than
      any frozen record the generator reads -- an output older than an
      input is stale by definition and needs no semantic knowledge to spot;
  S5  no generator run by S3 may write anything in the build root.  S3
      passes `--out <scratch>` on the strength of the string "--out"
      appearing in the generator's source, and `--out` is an unambiguous
      argparse prefix of `--outdir`: one generator therefore sent its
      figures to the scratch directory and its two .tex products here,
      after `retire_macros.py` had run, and 21 retired macros came back.
      Every generated product here is hashed before S3 and restored the
      moment it moves, and the generator is named.
  S3  re-running the generator into a scratch directory reproduces the
      fragment byte for byte, where the generator supports being pointed at
      one.  S2 catches staleness cheaply; S3 catches a fragment that was
      edited by hand or left behind by a generator that has since changed
      its mind.
  S3b ...and a generator that EXITS NON-ZERO is a failure of S3, not a
      skip.  Until r17 the return code was discarded and the comparison was
      guarded by `if os.path.exists(cand)` inside a bare
      `except Exception: pass`, so a generator that refused to run produced
      no candidate and was recorded as neither reproduced nor failed.  It
      was watched happening -- `persys_r17.py` refusing because the
      catalogue had not been rebuilt, and this gate saying nothing.
  S3c and a generator that exits zero and writes no fragment at all is a
      failure too, for the same reason: silence is not reproduction.

S2 is deliberately crude. A timestamp comparison knows nothing about what a
fragment means, which is exactly why it cannot be fooled by a fragment that
is internally consistent and wrong -- the failure mode both of the known
cases had.

    python3 fragstale.py [--drive N] [--quiet]

Exit 1 if any fragment is stale. --drive 1..6 breaks one clause each;
--drive 6 replaces every S3 generator call with `sys.exit(3)`, which must
make S3b fire on every fragment S3 can reach and never on any other clause.
"""
import glob
import json
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
HDR = re.compile(r'GENERATED by ([A-Za-z0-9_]+\.py)', re.I)
# Inputs every fragment depends on even when its own generator does not name
# them: the catalogue is the spine, and the frozen records are the analysis.
def _catalogue_of_record():
    """The one catalogue the manuscript names, not every file matching it.

    ★ The directory holds ten historical catalogues, and an unrelated
    generator rewrites one of them on every run, so globbing the pattern
    made the spine's timestamp jump and reported four current fragments as
    stale.  A gate that fires on a file nobody reads is worse than no gate:
    it trains its reader to ignore it.
    """
    try:
        import manuscript
        src = manuscript.flat()
    except Exception:
        src = ''
    named = re.findall(r'(per_target_results[\w.]*\.csv)', src)
    for n in named:
        p = os.path.join(HERE, n)
        if os.path.exists(p):
            return [p]
    c = sorted(glob.glob(os.path.join(HERE, 'per_target_results*.csv')))
    return c[-1:] if c else []


SPINE = (_catalogue_of_record()
         + sorted(glob.glob(os.path.join(HERE, 'r9inputs', '*.json'))))
# Fragments that are deliberately frozen copies of a retired generator's
# output: declared, with the reason, so "frozen" is a decision and not an
# absence of a generator.
FROZEN_OK = {}


def inputted():
    """Fragments the manuscript actually inputs, flattened."""
    try:
        import manuscript
        src = manuscript.flat()
    except Exception:
        src = ''
        for f in glob.glob(os.path.join(HERE, 'sections', '*.tex')):
            src += open(f, errors='ignore').read()
    names = set(re.findall(r'\\input\{([A-Za-z0-9_/]+)\}', src))
    out = []
    for n in sorted(names):
        p = os.path.join(HERE, n if n.endswith('.tex') else n + '.tex')
        if os.path.exists(p) and os.path.basename(p).startswith('tab'):
            out.append(p)
    return out


def main(argv):
    drive = 0
    quiet = '--quiet' in argv
    for i, a in enumerate(argv):
        if a == '--drive':
            drive = int(argv[i + 1])
    frags = inputted()
    stale, nogen, mismatch = [], [], []
    spine_mtime = max((os.path.getmtime(p) for p in SPINE), default=0)

    for f in frags:
        base = os.path.basename(f)
        head = ''.join(open(f, errors='ignore').readline() for _ in range(3))
        m = HDR.search(head)
        if drive == 1 and f is frags[0]:
            m = None
        gen = m.group(1) if m else None
        gpath = os.path.join(HERE, gen) if gen else None
        if gen is None or not os.path.exists(gpath):
            if base not in FROZEN_OK:
                nogen.append((base, gen or '(no header)'))
            continue
        ft = os.path.getmtime(f)
        gt = os.path.getmtime(gpath)
        if drive == 2 and not stale:
            gt = ft + 1
        older = []
        if gt > ft:
            older.append('its generator %s' % gen)
        if spine_mtime > ft:
            older.append('an input it depends on')
        if older:
            stale.append((base, gen, ', '.join(older)))

    # S3 -- byte reproduction, where the generator takes an output directory
    #
    # ★★★★ S3 WAS WRITING A PRODUCTION PATH, WHICH IS THE ONE THING A TEST IN
    # THIS TREE MAY NEVER DO.  It decides a generator can take a destination
    # by looking for the string "--out" in its source, and
    # `make_fig_context_v410.py` had only `--outdir` -- of which `--out` is an
    # unambiguous argparse prefix.  So S3 sent that generator's FIGURES to its
    # scratch directory and its two .tex products to the build root, AFTER
    # `retire_macros.py` had run, putting 21 retired macros back into the
    # layer and making the macro layer differ between two consecutive
    # `gate.sh` runs on an unchanged tree.  The generator now honours `--out`;
    # this records a digest of every generated product here before S3 and
    # requires that none of them move, so the NEXT generator to write outside
    # its own `--out` is named instead of silently undoing a build step.
    _guard = {}
    for _p in (sorted(glob.glob(os.path.join(HERE, 'survey_numbers*.tex')))
               + sorted(glob.glob(os.path.join(HERE, 'tab_*.tex')))):
        _guard[_p] = open(_p, 'rb').read()
    wrote = []
    repro = []
    #: ★ S3's two new verdicts, each its own list so the report says WHICH of
    #: the three ways a generator failed to reproduce its fragment.
    crashed = []        # exited non-zero, or timed out
    nowrite = []        # exited zero and wrote no fragment at all
    for f in frags:
        base = os.path.basename(f)
        head = ''.join(open(f, errors='ignore').readline() for _ in range(3))
        m = HDR.search(head)
        if not m:
            continue
        gen = m.group(1)
        gpath = os.path.join(HERE, gen)
        if not os.path.exists(gpath):
            continue        # already reported by S1
        gsrc = open(gpath, errors='ignore').read()
        if '--out' not in gsrc:
            continue
        d = tempfile.mkdtemp(prefix='fragstale_')
        # ★ The scratch directory must look like the build root to a
        # generator that writes a figure as well as a fragment, or `--out`
        # fails on a missing subdirectory and S3b reports a crash that is
        # the harness's and not the generator's.  Found the hour S3b was
        # written: `sens_r11.py` exited 1 on
        # `<scratch>/figures/sens_ring.pdf`.  Making the directory is the
        # honest fix; swallowing the return code was the old one.
        os.makedirs(os.path.join(d, 'figures'), exist_ok=True)
        try:
            cmd = [sys.executable, os.path.join(HERE, gen), '--out', d]
            if '--cat' in gsrc:
                cmd += ['--cat', HERE]
                for pk in ('per_target_results_v3.99.csv', 'starrv_v399.json',
                           'bary_v405.json', 'm3a_result_v400.json',
                           'freqocc_v405.json'):
                    cmd += ['--pick', pk]
            # ★★★★ S3 USED TO SWALLOW A CRASHING GENERATOR, ON EXACTLY THE
            # POPULATION IT WAS WRITTEN FOR.  The return code was discarded,
            # the comparison was wrapped in `if os.path.exists(cand)`, and
            # the whole block sat inside `except Exception: pass` -- so a
            # generator that EXITED NON-ZERO produced no candidate file and
            # was recorded as neither reproduced nor failed.  `r17-tables`
            # watched `persys_r17.py` refuse to run (correctly: it asserts
            # the catalogue has been rebuilt) and watched this gate report
            # nothing about it.  That is the project's commonest defect --
            # a check that cannot fail -- inside the gate whose job is
            # catching fragments that no longer reproduce.
            # Three ways to fail now, each distinguishable in the report:
            #   rc != 0        the generator refused or crashed
            #   no candidate   it exited zero and wrote nothing
            #   bytes differ   it wrote something else
            # ★ The `except` is narrowed to the subprocess call and is
            # itself a finding, so a timeout is no longer silence either.
            if drive == 6:
                cmd = [sys.executable, '-c', 'import sys; sys.exit(3)']
            try:
                cp = subprocess.run(cmd, capture_output=True, text=True,
                                    timeout=600)
                rc, err = cp.returncode, (cp.stderr or '').strip()
            except Exception as exc:          # timeout, OSError, ...
                rc, err = -1, '%s: %s' % (type(exc).__name__, exc)
            cand = os.path.join(d, base)
            if rc != 0:
                crashed.append((base, gen, rc,
                                err.splitlines()[-1][:160] if err else ''))
            elif not os.path.exists(cand):
                nowrite.append((base, gen))
            else:
                a = open(cand, 'rb').read()
                b = open(f, 'rb').read()
                if drive == 3:
                    b = b + b'\n'
                if a != b:
                    repro.append((base, gen))
        finally:
            import shutil
            shutil.rmtree(d, ignore_errors=True)
        # ...and the guard, checked after EVERY generator run and restored at
        # once, so a single run cannot leave the tree changed even while this
        # loop continues.
        for _p, _b in _guard.items():
            if not os.path.exists(_p) or open(_p, 'rb').read() != _b:
                wrote.append((gen, os.path.basename(_p)))
                with open(_p, 'wb') as _fh:
                    _fh.write(_b)
        mismatch = repro
    if drive == 5:
        #: outside the per-fragment loop, so the clause fires once rather than
        #: once per generator S3 happens to be able to run.
        wrote.append(('drive5_generator.py', 'survey_numbers_round0.tex'))

    # ★ S4 -- a SHADOW copy.  `\input{tab_selection}` resolves to the
    #   top-level file, while the generator writes `tables/tab_selection.tex`
    #   -- so the manuscript typesets whichever copy was left behind, and the
    #   live one is never read.  The two happen to be identical today, which
    #   is the whole danger: the shadow is invisible until the day they
    #   differ, and then the gate above cannot help because the stale file
    #   IS the one being typeset.
    shadow = []
    for f in frags:
        base = os.path.basename(f)
        alt = os.path.join(HERE, 'tables', base)
        if os.path.dirname(f) == HERE and os.path.exists(alt):
            same = open(f, 'rb').read() == open(alt, 'rb').read()
            older = os.path.getmtime(f) < os.path.getmtime(alt) - 1
            # TeX does not search `tables/`, so the top-level copy is the one
            # typeset and it cannot simply be deleted.  What it must never be
            # is a DIFFERENT file from the live one, or an older one.
            if not same or older:
                shadow.append((base, 'tables/' + base,
                               'differs' if not same else 'older'))
    if drive == 4:
        shadow.append(('drive', 'drive', 'drive'))
    fail = (len(stale) + len(nogen) + len(mismatch) + len(shadow)
            + len(wrote) + len(crashed) + len(nowrite))
    if not quiet:
        print('fragstale: %d generated fragments the manuscript inputs, '
              '%d spine inputs' % (len(frags), len(SPINE)))
        for b, g in nogen:
            print('  FAIL S1 %-28s declares no live generator (%s)' % (b, g))
        for b, g, why in stale:
            print('  FAIL S2 %-28s is older than %s' % (b, why))
        for b, g in mismatch:
            print('  FAIL S3 %-28s does not reproduce from %s' % (b, g))
        for b, g, rc, err in crashed:
            print('  FAIL S3b %-27s generator %s EXITED %s during the '
                  'reproduction run, so nothing was compared%s'
                  % (b, g, rc, (': ' + err) if err else ''))
        for b, g in nowrite:
            print('  FAIL S3c %-27s generator %s exited zero and wrote no '
                  'fragment into the scratch directory' % (b, g))
        for b, a, same in shadow:
            print('  FAIL S4 %-28s shadows %s, and \\input takes the '
                  'shadow (%s)' % (b, a, same))
        for g, b in wrote:
            print('  FAIL S5 %-28s was written in the build root by %s '
                  'during S3, which re-runs it into a scratch directory: a '
                  'test may not write a path production reads.  The file has '
                  'been restored from the digest taken before the run.'
                  % (b, g))
        print('fragstale: %d FAIL' % fail)
    return 1 if fail else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
